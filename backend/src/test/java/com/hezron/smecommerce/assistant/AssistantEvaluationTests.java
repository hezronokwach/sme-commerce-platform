/**
 * Scores the REAL assistant (Guide 7.3): real Gemini embeddings and real Groq answers, so it costs API
 * calls and never runs in the normal build or CI. It needs GEMINI_API_KEY and GROQ_API_KEY in backend/.env.
 * <pre>
 *   ./mvnw test -Dtest=AssistantEvaluationTests -Dassistant.eval=true
 * </pre>
 * The score and every answer are written to docs/assistant-evaluation.md.
 */
@EnabledIfSystemProperty(named = "assistant.eval", matches = "true")
@SpringBootTest
@AutoConfigureMockMvc
@Import(AssistantEvaluationTests.RealModelsDatabase.class)
@ActiveProfiles("test")
@TestPropertySource(properties = "app.assistant.questions-per-minute=1000")
class AssistantEvaluationTests {

    private static final String MAMA_MBOGA_POLICY = """
            Mama Mboga sells fresh vegetables in Nairobi. A sukuma bundle costs KES 50.
            We open at 7am on weekdays. We deliver on Sundays from 9am to 1pm.
            Delivery in Kilimani costs KES 100. We accept M-Pesa and card payments.
            You can return packed goods within 7 days. Cut vegetables cannot be returned.
            """;
    private static final String KAMAU_POLICY = """
            Kamau Hardware sells building materials. A bag of cement costs KES 750.
            We deliver building materials to Thika and Ruiru. We are closed on Sunday.
            Unused tools can be returned within 30 days with a receipt.
            """;

    @Autowired
    MockMvcTester mvc;

    @Autowired
    JdbcTemplate jdbc;

    @Test
    void scoreTheAssistant() throws Exception {
        Map<String, String> shops = new HashMap<>();
        shops.put("mamamboga", "Mama Mboga");
        shops.put("kamauhardware", "Kamau Hardware");
        teach(signUp("mamamboga", shops.get("mamamboga")), "Shop policy", MAMA_MBOGA_POLICY);
        teach(signUp("kamauhardware", shops.get("kamauhardware")), "Shop policy", KAMAU_POLICY);

        List<EvaluationCase> cases = EvaluationCase.load();
        StringBuilder rows = new StringBuilder();
        int passed = 0;
        for (EvaluationCase row : cases) {
            String answer = ask(row.shop(), row.question());
            boolean ok = row.passes(answer);
            if (ok) {
                passed = passed + 1;
            }
            String result = "FAIL";
            if (ok) {
                result = "pass";
            }
            rows.append("| ").append(row.shop()).append(" | ").append(row.question()).append(" | ").append(result)
                    .append(" | ").append(answer.replace('\n', ' ').replace("|", "/")).append(" |\n");
            Thread.sleep(2500); // stays inside the providers' free-tier rate limits
        }

        String report = "# Assistant evaluation\n\nScore: **" + passed + " of " + cases.size() + "**\n\n"
                + "Generated by `AssistantEvaluationTests` with real Gemini embeddings and Groq answers.\n\n"
                + "| Shop | Question | Result | Answer |\n| --- | --- | --- | --- |\n" + rows;
        Files.writeString(Path.of("..", "docs", "assistant-evaluation.md"), report, StandardCharsets.UTF_8);
        assertThat(cases).hasSize(15);
    }

    private String ask(String slug, String question) throws Exception {
        MvcTestResult result = mvc.post().uri("/api/store/" + slug + "/assistant/ask")
                .contentType(MediaType.APPLICATION_JSON)
                .content("{\"question\": \"" + question.replace("\"", "\\\"") + "\"}")
                .exchange();
        assertThat(result).hasStatus(HttpStatus.OK);
        return JsonPath.read(result.getResponse().getContentAsString(), "$.answer");
    }

    private void teach(String token, String title, String text) throws Exception {
        MockMultipartFile file = new MockMultipartFile("file", "policy.txt", MediaType.TEXT_PLAIN_VALUE,
                text.getBytes(StandardCharsets.UTF_8));
        MvcTestResult result = mvc.post().uri("/api/admin/assistant/documents")
                .header(HttpHeaders.AUTHORIZATION, "Bearer " + token)
                .multipart().file(file).param("title", title).exchange();
        assertThat(result).hasStatus(HttpStatus.ACCEPTED);
        String id = JsonPath.read(result.getResponse().getContentAsString(), "$.id");

        long giveUpAt = System.currentTimeMillis() + 60_000;
        while (System.currentTimeMillis() < giveUpAt) {
            String status = jdbc.queryForObject("SELECT status FROM assistant.documents WHERE id = ?::uuid",
                    String.class, id);
            if ("READY".equals(status)) {
                return;
            }
            if ("FAILED".equals(status)) {
                throw new AssertionError("Embedding failed: is GEMINI_API_KEY set in backend/.env?");
            }
            Thread.sleep(200);
        }
        throw new AssertionError("The document never became READY");
    }

    private String signUp(String slug, String name) throws Exception {
        MvcTestResult result = mvc.post().uri("/api/auth/signup")
                .contentType(MediaType.APPLICATION_JSON)
                .content("""
                        {"shopName": "%s", "shopSlug": "%s", "ownerName": "Owner",
                         "email": "%s@example.com", "password": "a-long-password"}
                        """.formatted(name, slug, slug))
                .exchange();
        assertThat(result).hasStatus(HttpStatus.CREATED);
        return JsonPath.read(result.getResponse().getContentAsString(), "$.accessToken");
    }

    /** Only the database: unlike TestcontainersConfiguration, it leaves the real AI models in place. */
    @TestConfiguration(proxyBeanMethods = false)
    static class RealModelsDatabase {

        @Bean
        @ServiceConnection
        PostgreSQLContainer postgresContainer() {
            return new PostgreSQLContainer(DockerImageName.parse("pgvector/pgvector:pg17")
                    .asCompatibleSubstituteFor("postgres"));
        }
    }

}
